CREATE TABLE TB_CLIENTE(
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(150) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    cpf VARCHAR2(11),
    ativo CHAR(1) DEFAULT 'S',
    CONSTRAINT PK_TB_CLIENTE_ID PRIMARY KEY (id_cliente),
    CONSTRAINT UQ_TB_CLIENTE_EMAIL UNIQUE (email),
    CONSTRAINT UQ_TB_CLIENTE_CPF UNIQUE (cpf),
    CONSTRAINT CHK_TB_CLIENTE_ATIVO CHECK (ativo IN ('S','N'))
)
CREATE TABLE TB_VENDEDOR(
    id_vendedor NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(150) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    ativo CHAR(1) DEFAULT 'S',
    CONSTRAINT PK_TB_VENDEDOR_ID PRIMARY KEY (id_vendedor),
    CONSTRAINT UQ_TB_VENDEDOR_EMAIL UNIQUE (email),
    CONSTRAINT CHK_TB_VENDEDOR_ATIVO CHECK (ativo IN ('S','N'))
)
CREATE TABLE TB_CATEGORIA(
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_TB_CATEGORIA_ID PRIMARY KEY (id_categoria)
)
CREATE TABLE TB_PRODUTO(
    id_produto NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_categoria NUMBER NOT NULL,
    sku VARCHAR2(30) NOT NULL,
    nome VARCHAR2(255) NOT NULL,
    preco_unit NUMBER(12,2),
    CONSTRAINT PK_TB_PRODUTO_ID PRIMARY KEY (id_produto),
    CONSTRAINT FK_TB_PRODUTO_ID_CATEGORIA FOREIGN KEY (id_categoria) REFERENCES TB_CATEGORIA(id_categoria),
    CONSTRAINT UQ_TB_PRODUTO_SKU UNIQUE (sku),
    CONSTRAINT CK_TB_PRODUTO_PRECO CHECK(preco_unit>0)
)
CREATE TABLE TB_VENDA(
    id_venda NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente NUMBER NOT NULL,
    id_vendedor NUMBER NOT NULL,
    dt_venda DATE DEFAULT SYSDATE NOT NULL,
    valor_liquido NUMBER(12,2),
    canal VARCHAR2(8),
    status VARCHAR2(9),
    CONSTRAINT PK_TB_VENDA_ID PRIMARY KEY (id_venda),
    CONSTRAINT FK_TB_VENDA_ID_CLIENTE FOREIGN KEY (id_cliente) REFERENCES TB_CLIENTE(id_cliente),
    CONSTRAINT FK_TB_VENDA_ID_VENDEDOR FOREIGN KEY (id_vendedor) REFERENCES TB_VENDEDOR(id_vendedor),
    CONSTRAINT CHK_TB_VENDA_CANAL CHECK (canal IN ('APP','SITE','LOJA', 'TELEFONE')),
    CONSTRAINT CHK_TB_VENDA_STATUS CHECK (status IN ('ABERTA','FECHADA','CANCELADA'))
)
CREATE TABLE TB_VENDA_ITEM(
    id_venda_item NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_venda NUMBER NOT NULL,
    id_produto NUMBER NOT NULL,
    quantidade NUMBER NOT NULL,
    valor_unit NUMBER(12,2) NOT NULL,
    percentual_desconto NUMBER(5,2) DEFAULT 0,
    valor_total NUMBER(12,2),
    CONSTRAINT PK_TB_VENDA_ITEM_ID PRIMARY KEY (id_venda_item),
    CONSTRAINT FK_TB_VENDA_ITEM_ID_VENDA FOREIGN KEY (id_venda) REFERENCES TB_VENDA(id_venda) ON DELETE CASCADE,
    CONSTRAINT FK_TB_VENDA_ITEM_ID_PRODUTO FOREIGN KEY (id_produto) REFERENCES TB_PRODUTO(id_produto),
    CONSTRAINT CHK_TB_VENDA_ITEM_QUANTIDADE CHECK(quantidade>0),
    CONSTRAINT CHK_TB_VENDA_ITEM_PERCENTUAL_DESCONTO CHECK(percentual_desconto BETWEEN 0 AND 50)
)