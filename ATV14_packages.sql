/*ADIÇAO A ESPECIFICAÇAO DO PACOTE*/
CREATE OR REPLACE PACKAGE PKG_GESTAO_VENDAS AS
    C_TAXA_DESCONTO_PADRAO CONSTANT NUMBER:=0.05;
    E_ESTOQUE_INSUFICIENTE EXCEPTION;

    PROCEDURE REALIZAR_VENDA(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER, P_VALOR_FINAL OUT NUMBER);
    PROCEDURE REALIZAR_VENDA(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER, P_DESCONTO_PCT IN NUMBER, P_VALOR_FINAL OUT NUMBER);
    FUNCTION VERIFICAR_DISPONIBILIDADE(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER) RETURN BOOLEAN;
    FUNCTION FATURAMENTO_DIARIO RETURN NUMBER;
    PROCEDURE REPOR_ESTOQUE(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER); /*NOVO PROCEDURE, EXERCICIO 1*/
END PKG_GESTAO_VENDAS;

/*ADIÇAO AO CORPO DO PACOTE*/
CREATE OR REPLACE PACKAGE BODY PKG_GESTAO_VENDAS AS
    G_TOTAL_VENDAS_SESSAO NUMBER:=0;

    PROCEDURE REGISTRAR_BAIXA_ESTOQUE(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER) IS
    BEGIN
        UPDATE TB_PROD_ESTOQUE
        SET QTD_ESTOQUE=QTD_ESTOQUE-P_QUANTIDADE
        WHERE ID_PRODUTO=P_ID_PRODUTO;
    END REGISTRAR_BAIXA_ESTOQUE;

    FUNCTION VERIFICAR_DISPONIBILIDADE(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER) RETURN BOOLEAN IS
        V_ESTOQUE_ATUAL NUMBER:=0;
    BEGIN
        SELECT QTD_ESTOQUE INTO V_ESTOQUE_ATUAL
        FROM TB_PROD_ESTOQUE
        WHERE ID_PRODUTO=P_ID_PRODUTO;

        RETURN (V_ESTOQUE_ATUAL>=P_QUANTIDADE);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN FALSE;
    END VERIFICAR_DISPONIBILIDADE;

    PROCEDURE REALIZAR_VENDA(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER, P_VALOR_FINAL OUT NUMBER) IS
    BEGIN
        REALIZAR_VENDA(P_ID_PRODUTO, P_QUANTIDADE, 0, P_VALOR_FINAL);
    END REALIZAR_VENDA;

    PROCEDURE REALIZAR_VENDA(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER, P_DESCONTO_PCT IN NUMBER, P_VALOR_FINAL OUT NUMBER) IS
        V_PRECO_UNITARIO NUMBER(10,2);
        V_TOTAL_BRUTO NUMBER(12,2);
    BEGIN
        IF NOT VERIFICAR_DISPONIBILIDADE(P_ID_PRODUTO, P_QUANTIDADE) THEN
            RAISE E_ESTOQUE_INSUFICIENTE;
        END IF;

        SELECT PRECO INTO V_PRECO_UNITARIO
        FROM TB_PROD_ESTOQUE
        WHERE ID_PRODUTO=P_ID_PRODUTO;

        V_TOTAL_BRUTO:=V_PRECO_UNITARIO*P_QUANTIDADE;
        P_VALOR_FINAL:=V_TOTAL_BRUTO-(V_TOTAL_BRUTO*NVL(P_DESCONTO_PCT, 0));

        REGISTRAR_BAIXA_ESTOQUE(P_ID_PRODUTO, P_QUANTIDADE);

        INSERT INTO TB_REGISTRO_VENDAS(ID_PRODUTO, QTD_VENDIDA, VALOR_VENDA)
        VALUES(P_ID_PRODUTO, P_QUANTIDADE, P_VALOR_FINAL);

        G_TOTAL_VENDAS_SESSAO:=G_TOTAL_VENDAS_SESSAO+1;

        COMMIT;
    EXCEPTION
        WHEN E_ESTOQUE_INSUFICIENTE THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20010, 'ESTOQUE INSUFICIENTE PARA ATENDER À QUANTIDADE SOLICITADA.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20099, 'ERRO AO PROCESSAR VENDA NO PACOTE: '||SQLERRM);
    END REALIZAR_VENDA;

    FUNCTION FATURAMENTO_DIARIO RETURN NUMBER IS
        V_FATURAMENTO NUMBER(12,2):=0;
    BEGIN
        SELECT NVL(SUM(VALOR_VENDA), 0) INTO V_FATURAMENTO
        FROM TB_REGISTRO_VENDAS
        WHERE TRUNC(DATA_VENDA)=TRUNC(SYSDATE);

        RETURN V_FATURAMENTO;
    END FATURAMENTO_DIARIO;

    /*NOVA PROCEDURE, EXERCICIO 1-INICIO*/
    PROCEDURE REPOR_ESTOQUE(P_ID_PRODUTO IN NUMBER, P_QUANTIDADE IN NUMBER) IS
    BEGIN
        IF P_QUANTIDADE<=0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'NÃO PODE SER NEGATIVO');
        END IF;

        UPDATE TB_PROD_ESTOQUE
        SET QTD_ESTOQUE=QTD_ESTOQUE+P_QUANTIDADE
        WHERE ID_PRODUTO=P_ID_PRODUTO;

        IF SQL%ROWCOUNT=0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'PRODUTO NÃO ENCONTRADO');
        END IF;

        COMMIT;
    END REPOR_ESTOQUE;
/*NOVA PROCEDURE, EXERCICIO 1-FIM*/
BEGIN
    G_TOTAL_VENDAS_SESSAO:=0;
END PKG_GESTAO_VENDAS;

